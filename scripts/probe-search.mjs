import { mkdir, writeFile } from 'node:fs/promises';
const origin = 'https://videosearch.webber.qzz.io';
const query = process.argv[2] || '海市蜃楼';
const url = new URL('/v1/search', origin);
url.search = new URLSearchParams({ q: query, view: 'series', platforms: process.argv[3] || 'all', limit: '20' });
const response = await fetch(url, { headers: { 'User-Agent': 'CrayonPlayer VideoSearch probe' }, signal: AbortSignal.timeout(30000) });
if (!response.ok) throw new Error(`VideoSearch HTTP ${response.status}`);
const result = await response.json();
await mkdir('.parser-inspection/search', { recursive: true });
await writeFile('.parser-inspection/search/videosearch.json', JSON.stringify(result, null, 2));
console.log(JSON.stringify({ total: result.total, partial: result.partial, providers: result.providers }));
for (const series of result.results || []) console.log(JSON.stringify({ title: series.title, year: series.year, platform: series.platform, detail_url: series.detail_url }));
